"""
quantize.py - post-training INT8 quantization of the float MLP, and export of
everything the hardware and testbenches need.

    python model/quantize.py

Reads   model/float_model.npz
Writes  model/quant_model.npz          integer model used by golden.py
        model/quant_report.txt         float vs INT8 accuracy
        rtl/npu_model_params.svh       layer sizes and requantization constants
        mem/N<n>/weights.mem           weight ROM image for an n x n array
        mem/N<n>/bias.mem              bias ROM image for an n x n array
        mem/test_images.mem            10,000 MNIST test images
        mem/golden.mem                 label, expected prediction, expected logits

Quantization scheme (symmetric, per-tensor):
  weights      W_q = round(W / s_w),  s_w = max|W| / 127
  biases       B_q = round(b / (s_w * s_in))           (int32)
  activations  s_out from the largest activation seen on 10,000 training images
  rescale      M / 2^S ~= s_w * s_in / s_out,  M in [2^14, 2^15)
"""
import os

import numpy as np

import golden
import mnist

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FLOAT_FILE = os.path.join(HERE, "float_model.npz")
ARRAY_SIZES = [1, 2, 4, 8, 16]
CALIB_IMAGES = 10000
INPUT_SCALE = 2.0 / 255.0     # x_real = pixel / 255 ~= (pixel >> 1) * 2 / 255


def choose_m_s(real):
    """Integer multiplier M and shift S with M / 2^S ~= real, M in [2^14, 2^15)."""
    s = 0
    while real * (1 << (s + 1)) < (1 << 15):
        s += 1
    m = int(round(real * (1 << s)))
    if m >= (1 << 15):
        m >>= 1
        s -= 1
    return m, s


def quantize(fm, calib_x):
    n_layers = len([k for k in fm.files if k.startswith("w")])
    s_in = INPUT_SCALE
    x_float = calib_x.astype(np.float64) / 255.0
    layers = []
    for l in range(n_layers):
        w = fm["w{}".format(l)].astype(np.float64)
        b = fm["b{}".format(l)].astype(np.float64)
        relu = l < n_layers - 1

        s_w = np.abs(w).max() / 127.0
        w_q = np.clip(np.round(w / s_w), -127, 127).astype(np.int64)
        b_q = np.round(b / (s_w * s_in)).astype(np.int64)

        y_float = x_float @ w.T + b
        if relu:
            y_float = np.maximum(y_float, 0.0)
        s_out = np.abs(y_float).max() / 127.0
        m, s = choose_m_s(s_w * s_in / s_out)

        layers.append({"W": w_q, "B": b_q, "M": m, "S": s, "relu": relu,
                       "s_w": s_w, "s_in": s_in, "s_out": s_out})
        x_float = y_float
        s_in = s_out
    return layers


def float_accuracy(fm, x, y):
    h = x.astype(np.float64) / 255.0
    n_layers = len([k for k in fm.files if k.startswith("w")])
    for l in range(n_layers):
        h = h @ fm["w{}".format(l)].T + fm["b{}".format(l)]
        if l < n_layers - 1:
            h = np.maximum(h, 0.0)
    return float((h.argmax(axis=1) == y).mean())


def write_hex_lines(path, words, hex_digits):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    mask = (1 << (4 * hex_digits)) - 1
    with open(path, "w") as f:
        for w in words:
            f.write("{:0{}x}\n".format(int(w) & mask, hex_digits))


def pack_bytes(values):
    """Pack int values into one integer, element i in bits [8i+7 : 8i]."""
    word = 0
    for i, v in enumerate(values):
        word |= (int(v) & 0xFF) << (8 * i)
    return word


def export_array_images(layers, n):
    """Weight and bias ROM images for an n x n systolic array."""
    weight_words = []
    bias_words = []
    for layer in layers:
        out_dim, in_dim = layer["W"].shape
        tiles = -(-out_dim // n)
        w_pad = np.zeros((tiles * n, in_dim), dtype=np.int64)
        w_pad[:out_dim] = layer["W"]
        b_pad = np.zeros(tiles * n, dtype=np.int64)
        b_pad[:out_dim] = layer["B"]
        for t in range(tiles):
            for k in range(in_dim):
                weight_words.append(pack_bytes(w_pad[t * n:(t + 1) * n, k]))
        bias_words += list(b_pad)
    d = os.path.join(ROOT, "mem", "N{}".format(n))
    write_hex_lines(os.path.join(d, "weights.mem"), weight_words, 2 * n)
    write_hex_lines(os.path.join(d, "bias.mem"), bias_words, 8)
    return len(weight_words), len(bias_words)


def export_params_svh(layers):
    dims = [layers[0]["W"].shape[1]] + [l["W"].shape[0] for l in layers]
    lines = [
        "// npu_model_params.svh - GENERATED by model/quantize.py, do not edit.",
        "// Layer sizes and requantization constants of the INT8 MLP.",
        "localparam int IN_DIM  = {};".format(dims[0]),
        "localparam int H1_DIM  = {};".format(dims[1]),
        "localparam int H2_DIM  = {};".format(dims[2]),
        "localparam int OUT_DIM = {};".format(dims[3]),
    ]
    for l, layer in enumerate(layers):
        lines.append("localparam int L{}_M = {};   // requant multiplier".format(l + 1, layer["M"]))
        lines.append("localparam int L{}_S = {};   // requant shift".format(l + 1, layer["S"]))
    path = os.path.join(ROOT, "rtl", "npu_model_params.svh")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def export_test_vectors(layers, vx, vy):
    logits, preds = golden.infer(layers, vx)
    with open(os.path.join(ROOT, "mem", "test_images.mem"), "w") as f:
        for img in vx:
            for q in range(0, 784, 16):
                f.write("{:032x}\n".format(pack_bytes(img[q:q + 16])))
    with open(os.path.join(ROOT, "mem", "golden.mem"), "w") as f:
        for label, pred, lg in zip(vy, preds, logits):
            f.write("{:x} {:x} {:020x}\n".format(int(label), int(pred), pack_bytes(lg)))
    return logits, preds


def main():
    tx, _, vx, vy = mnist.load()
    fm = np.load(FLOAT_FILE)
    layers = quantize(fm, tx[:CALIB_IMAGES])

    np.savez(os.path.join(HERE, "quant_model.npz"), n_layers=len(layers),
             **{"W{}".format(l): layer["W"].astype(np.int8) for l, layer in enumerate(layers)},
             **{"B{}".format(l): layer["B"].astype(np.int32) for l, layer in enumerate(layers)},
             **{"M{}".format(l): layer["M"] for l, layer in enumerate(layers)},
             **{"S{}".format(l): layer["S"] for l, layer in enumerate(layers)},
             **{"relu{}".format(l): layer["relu"] for l, layer in enumerate(layers)})

    export_params_svh(layers)
    for n in ARRAY_SIZES:
        nw, nb = export_array_images(layers, n)
        print("N={:2d}: weight ROM {:5d} x {:3d} bits, bias ROM {:3d} x 32 bits".format(n, nw, 8 * n, nb))
    _, preds = export_test_vectors(layers, vx, vy)

    acc_float = float_accuracy(fm, vx, vy)
    acc_int = float((preds == vy).mean())
    report = [
        "TinyNPU model quantization report",
        "Network: 784 -> 128 -> 64 -> 10 (ReLU), INT8 weights/activations, INT32 accumulation",
        "Float32 test accuracy : {:.2f}%".format(100 * acc_float),
        "INT8    test accuracy : {:.2f}%  ({} / {} images)".format(100 * acc_int, int((preds == vy).sum()), len(vy)),
        "",
        "layer  M      S   s_w        s_in       s_out",
    ]
    for l, layer in enumerate(layers):
        report.append("{:5d}  {:5d}  {:2d}  {:.3e}  {:.3e}  {:.3e}".format(
            l + 1, layer["M"], layer["S"], layer["s_w"], layer["s_in"], layer["s_out"]))
    x = golden.quantize_input(vx)
    max_acc = 0
    for layer in layers:
        acc = x @ layer["W"].T + layer["B"]
        max_acc = max(max_acc, int(np.abs(acc).max()))
        x = golden.requant(acc, layer["M"], layer["S"], layer["relu"])
    report.append("largest |accumulator| on the test set: {:,} ({} bits incl. sign; hardware has 32)".format(
        max_acc, max_acc.bit_length() + 1))
    text = "\n".join(report)
    with open(os.path.join(HERE, "quant_report.txt"), "w") as f:
        f.write(text + "\n")
    print(text)


if __name__ == "__main__":
    main()
